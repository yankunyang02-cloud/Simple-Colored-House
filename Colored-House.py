import turtle
t = turtle.Turtle()
t.penup()
for i in range(1):
    t.goto(-100, -100)
t.pendown()
t.fillcolor("wheat")
t.begin_fill()
t.goto(100, -100)
t.left(90)
t.forward(200)
t.left(90)
t.forward(200)
t.left(90)
t.forward(200)
t.end_fill()
t.penup()
t.goto(-130, 100)
t.pendown()
t.fillcolor("brown")
t.begin_fill()
t.left(130)
t.forward(160)
t.right(80)
t.forward(160)
t.right(5)
t.left(90)
t.end_fill()
t.penup()
t.goto(25, -100)
t.pendown()
t.fillcolor("red")
t.begin_fill()
t.left(45)
t.forward(90)
t.right(90)
t.forward(60)
t.right(90)
t.forward(90)
t.end_fill()
t.penup()
t.goto(-65, -20)
t.pendown()
t.fillcolor("blue")
t.begin_fill()
t.left(90)
t.forward(50)
t.left(90)
t.forward(50)
t.left(90)
t.forward(50)
t.left(90)
t.forward(50)
t.end_fill()
t.penup()
t.goto(-40, -20)
t.pendown()
t.forward(-50)
t.penup()
t.goto(-65, 5)
t.pendown()
t.left(90)
t.forward(50)
t.hideturtle()

turtle.done()
